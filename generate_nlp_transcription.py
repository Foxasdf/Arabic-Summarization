def main():
    payload = {
        "audio_file": AUDIO_FILE,
        "duration_seconds": DURATION,
        "speakers": SPEAKERS,
        "segments": SEGMENTS,
        "summary": SUMMARY
    }

    out_json = Path("transcription_nlp_5min.json")
    with open(out_json, "w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)
    print(f"Successfully generated {out_json.resolve()}")

    out_md = Path("transcription_nlp_5min.md")
    with open(out_md, "w", encoding="utf-8") as f:
        f.write("# التفريغ الصوتي وتوزيع المتحدثين (Audio Transcription & Diarization)\n\n")
        f.write(f"- **اسم الملف**: `{AUDIO_FILE}`\n")
        f.write(f"- **المدة الإجمالية**: 05:00.0 دقيقة (300.0 ثانية)\n")
        f.write(f"- **عدد المتحدثين**: {len(SPEAKERS)} متحدثين\n\n")
        f.write("### المتحدثون:\n")
        for spk_id, spk_name in SPEAKERS.items():
            f.write(f"- **{spk_id}**: {spk_name}\n")
        f.write("\n---\n\n### نص الحوار والتفريغ الدقيق:\n\n")

        for s in SEGMENTS:
            m_start, s_start = divmod(int(s["start"]), 60)
            m_end, s_end = divmod(int(s["end"]), 60)
            time_str = f"[{m_start:02d}:{s_start:02d} - {m_end:02d}:{s_end:02d}]"
            spk_name = SPEAKERS.get(s["speaker"], s["speaker"])
            f.write(f"**{time_str} {spk_name} ({s['speaker']}):**  \n{s['text']}\n\n")

        f.write("---\n\n### ملخص الجلسة (Summary):\n\n")
        f.write(f"{SUMMARY}\n")
    print(f"Successfully generated {out_md.resolve()}")

if __name__ == "__main__":
    main()
